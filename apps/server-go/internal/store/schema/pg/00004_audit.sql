-- 由 schema_version 23 的真实库结构整理；任何环境执行后应得到同一结构。

-- audit_logs
CREATE TABLE audit_logs (
  -- rowid：单调序号。SQLite 的隐式 rowid 在 PostgreSQL 里显式化，并允许调用方插入 NULL
  -- （outbox 物化等内部路径按全列插入，identity 必须以 DEFAULT 生成而不是拒绝 NULL）。
  rowid              bigint GENERATED BY DEFAULT AS IDENTITY,
  id                 text NOT NULL,
  org_id             text NOT NULL,
  actor_id           text NOT NULL,
  actor_name         text NOT NULL DEFAULT ''::text,
  actor_type         text NOT NULL DEFAULT 'user'::text,
  action             text NOT NULL,
  resource           text NOT NULL,
  metadata           text NOT NULL DEFAULT '{}'::text,
  ip                 text NOT NULL DEFAULT ''::text,
  user_agent         text NOT NULL DEFAULT ''::text,
  request_id         text NOT NULL DEFAULT ''::text,
  prev_hash          text NOT NULL DEFAULT ''::text,
  entry_hash         text NOT NULL DEFAULT ''::text,
  created_at         text NOT NULL DEFAULT to_char(timezone('UTC'::text, clock_timestamp()), 'YYYY-MM-DD HH24:MI:SS'::text),
  PRIMARY KEY (id),
  CONSTRAINT audit_logs_rowid_key UNIQUE (rowid)
);

-- audit_heads
CREATE TABLE audit_heads (
  org_id             text NOT NULL,
  revision           bigint NOT NULL DEFAULT 0,
  PRIMARY KEY (org_id)
);

-- audit_checkpoints
CREATE TABLE audit_checkpoints (
  id                 text NOT NULL,
  org_id             text NOT NULL,
  last_id            text NOT NULL,
  last_hash          text NOT NULL,
  hmac               text NOT NULL,
  created_at         text NOT NULL DEFAULT to_char(timezone('UTC'::text, clock_timestamp()), 'YYYY-MM-DD HH24:MI:SS'::text),
  PRIMARY KEY (id)
);

-- audit_exports
CREATE TABLE audit_exports (
  id                 text NOT NULL,
  org_id             text NOT NULL,
  actor_id           text NOT NULL,
  format             text NOT NULL,
  filters            text NOT NULL DEFAULT '{}'::text,
  status             text NOT NULL DEFAULT 'pending'::text,
  file_path          text NOT NULL DEFAULT ''::text,
  row_count          bigint NOT NULL DEFAULT 0,
  error              text NOT NULL DEFAULT ''::text,
  created_at         text NOT NULL DEFAULT to_char(timezone('UTC'::text, clock_timestamp()), 'YYYY-MM-DD HH24:MI:SS'::text),
  completed_at       text,
  lease_token        text NOT NULL DEFAULT ''::text,
  lease_until        bigint NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  CONSTRAINT audit_exports_format_check CHECK ((format = ANY (ARRAY['csv'::text, 'jsonl'::text]))),
  CONSTRAINT audit_exports_status_check CHECK ((status = ANY (ARRAY['pending'::text, 'done'::text, 'failed'::text])))
);

-- mutation_receipts
CREATE TABLE mutation_receipts (
  org_id             text NOT NULL,
  actor_id           text NOT NULL,
  request_key        text NOT NULL,
  request_hash       text NOT NULL,
  response           text NOT NULL,
  PRIMARY KEY (org_id, actor_id, request_key),
  CONSTRAINT mutation_receipts_org_id_fkey FOREIGN KEY (org_id) REFERENCES orgs(id) ON DELETE CASCADE
);

-- outbox_events
-- 事件总线：密钥变更先在同一事务写入，再由任意副本认领派发。
-- RLS 在 95-rls.sql 里打开；事件派发走控制连接，不授予运行角色。
CREATE TABLE outbox_events (
  id                 text NOT NULL,
  org_id             text NOT NULL,
  event_id           text NOT NULL,
  kind               text NOT NULL DEFAULT 'secret'::text,
  payload            text NOT NULL,
  status             text NOT NULL DEFAULT 'pending'::text,
  error              text NOT NULL DEFAULT ''::text,
  created_at         text NOT NULL DEFAULT to_char(timezone('UTC'::text, clock_timestamp()), 'YYYY-MM-DD HH24:MI:SS'::text),
  event_sequence     bigint NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  CONSTRAINT outbox_events_status_check CHECK ((status = ANY (ARRAY['pending'::text, 'done'::text, 'dead'::text])))
);

-- 索引
CREATE INDEX IF NOT EXISTS idx_audit_cp_org ON audit_checkpoints (org_id, created_at);
CREATE INDEX IF NOT EXISTS idx_audit_exports_org ON audit_exports (org_id);
CREATE INDEX IF NOT EXISTS idx_audit_org_time ON audit_logs (org_id, created_at);
CREATE INDEX IF NOT EXISTS idx_outbox_pending ON outbox_events (status, created_at);
